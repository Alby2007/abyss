export const TIER_COLOR = { 0: '#ff8a7a', 1: '#d5f2ec', 2: '#7cf3ff', 3: '#9fb0ff', 4: '#c88cff', 5: '#ff7db8', 6: '#ffb547' };

export function creatureSvg(tier, px = 6) {
  const rows = ART[tier] || ART[0];
  const w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const c = TIER_COLOR[tier] || TIER_COLOR[0];
  let rects = '';
  rows.forEach((r, yy) => [...r].forEach((ch, xx) => {
    if (ch === '#') rects += `<rect x="${xx}" y="${yy}" width="1.02" height="1.02" fill="${c}"/>`;
    if (ch === 'o') rects += `<rect x="${xx}" y="${yy}" width="1.02" height="1.02" fill="#fff"/>`;
  }));
  return `<svg class="creature" viewBox="0 0 ${w} ${h}" width="${w * px}" height="${h * px}" shape-rendering="crispEdges" style="filter:drop-shadow(0 0 12px ${c}88)" aria-hidden="true">${rects}</svg>`;
}
